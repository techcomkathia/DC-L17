//contar de 1 a 10 utilizando o laço de repetição while
let numeroInicial = 1
let numeroFinal = 10

while (numeroInicial <= numeroFinal){
    console.log(numeroInicial)
    // atualizar a variável que controla o laço
     numeroInicial++
}

console.log('Esse código só será executado depois do laço finalizado')

